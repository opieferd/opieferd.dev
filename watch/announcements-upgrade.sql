-- Dynamic Opie Watch announcements
-- Run once in Supabase Dashboard -> SQL Editor.
create table if not exists public.announcements (
    id bigint generated by default as identity primary key,
    title text not null check (char_length(title) between 1 and 120),
    body text not null check (char_length(body) between 1 and 2000),
    show_normal boolean not null default true,
    show_gold boolean not null default false,
    enabled boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint announcements_has_audience check (show_normal or show_gold)
);

alter table public.announcements enable row level security;
grant select on public.announcements to anon, authenticated;
grant insert, update, delete on public.announcements to authenticated;
grant usage, select on sequence public.announcements_id_seq to authenticated;

drop policy if exists "announcements public read enabled" on public.announcements;
create policy "announcements public read enabled"
    on public.announcements for select to anon, authenticated
    using (enabled = true);

drop policy if exists "announcements owner manage" on public.announcements;
create policy "announcements owner manage"
    on public.announcements for all to authenticated
    using (public.is_owner())
    with check (public.is_owner());

